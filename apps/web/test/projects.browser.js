async (page) => {
  const baseUrl = 'http://127.0.0.1:5173';
  const run = Date.now();
  const password = `Projects-${run}-Aa!`;
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(baseUrl + '/login');
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  async function call(method, path, body, token, expected = 200) {
    const options = { data: body, headers: {} };
    if (token) options.headers.Authorization = `Bearer ${token}`;
    const response = await page.request[method](baseUrl + '/api' + path, options);
    assert(response.status() === expected, `${method} ${path}: ${response.status()}`);
    return response.json();
  }
  async function account(role, suffix) {
    const email = `projects-${suffix}-${run}@example.com`;
    const user = await call('post', '/auth/register', { name: 'Перевірка проєкту ' + suffix, email, password, role }, null, 201);
    const login = await call('post', '/auth/login', { email, password });
    return { ...user, token: login.accessToken };
  }
  async function signIn(user) {
    await page.evaluate(() => sessionStorage.clear());
    await page.goto(baseUrl + '/login');
    await page.getByLabel('Електронна пошта', { exact: true }).fill(user.email);
    await page.getByLabel('Пароль', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Увійти', exact: true }).click();
    await page.waitForURL(baseUrl + '/');
    await page.getByTestId('active-projects').waitFor();
  }
  const client = await account('CLIENT', 'owner');
  const freelancer = await account('FREELANCER', 'member');
  const outsider = await account('CLIENT', 'outsider');
  await signIn(client);
  await page.getByRole('link', { name: 'Мої проєкти', exact: true }).click();
  await page.getByRole('link', { name: 'Створити проєкт', exact: true }).click();
  await page.getByLabel('Назва проєкту', { exact: true }).fill('   ');
  await page.getByRole('button', { name: 'Зберегти проєкт' }).click();
  await page.getByRole('alert').filter({ hasText: 'Назва має містити' }).waitFor();
  const title = `Проєкт із форми ${run}`;
  await page.getByLabel('Назва проєкту', { exact: true }).fill(title);
  await page.getByLabel('Опис', { exact: true }).fill('Реальний опис\nДругий рядок');
  await page.getByLabel('Дедлайн', { exact: true }).fill('2027-10-20T15:30');
  await page.route('**/api/projects', (route) => route.abort());
  await page.getByRole('button', { name: 'Зберегти проєкт' }).click();
  await page.getByRole('alert').waitFor();
  assert(await page.getByLabel('Назва проєкту', { exact: true }).inputValue() === title, 'Failed submit must preserve fields');
  await page.unroute('**/api/projects');
  await page.getByRole('button', { name: 'Зберегти проєкт' }).click();
  await page.waitForURL(/\/projects\/[0-9a-f-]+$/);
  await page.getByRole('heading', { name: title, exact: true }).waitFor();
  const id = page.url().split('/').pop();
  let project = await call('get', `/projects/${id}`, undefined, client.token);
  assert(project.title === title && project.description.includes('\n'), 'Project form writes database fields');
  assert(new Date(project.deadline).getTime() === new Date('2027-10-20T15:30:00').getTime(), 'Deadline uses browser local time');
  await call('post', `/projects/${id}/members`, { userId: freelancer.id }, client.token, 201);
  await call('post', `/projects/${id}/tasks`, { title: 'Перевірити головну сторінку', assigneeId: freelancer.id, priority: 'HIGH', deadline: '2027-10-19T10:00:00Z' }, client.token, 201);
  await page.getByRole('button', { name: 'Оновити дані' }).click();
  await page.getByRole('cell', { name: 'Перевірити головну сторінку', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Учасники проєкту', exact: true }).waitFor();
  await page.getByLabel('Пріоритет', { exact: true }).selectOption('LOW');
  await page.getByRole('heading', { name: 'Завдань не знайдено' }).waitFor();
  await page.getByLabel('Пріоритет', { exact: true }).selectOption('HIGH');
  await page.getByRole('cell', { name: 'Перевірити головну сторінку', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Редагувати проєкт', exact: true }).click();
  await page.getByLabel('Назва проєкту', { exact: true }).fill(title + ' — оновлено');
  await page.getByLabel('Статус', { exact: true }).selectOption('ACTIVE');
  await page.getByLabel('Дедлайн', { exact: true }).fill('2027-10-18T15:30');
  await page.getByRole('button', { name: 'Зберегти проєкт' }).click();
  await page.getByRole('alert').filter({ hasText: 'Дедлайн проєкту не може бути раніше' }).waitFor();
  await page.getByLabel('Дедлайн', { exact: true }).fill('');
  await page.getByLabel('Опис', { exact: true }).fill('');
  await page.getByRole('button', { name: 'Зберегти проєкт' }).click();
  await page.getByRole('heading', { name: title + ' — оновлено', exact: true }).waitFor();
  project = await call('get', `/projects/${id}`, undefined, client.token);
  assert(project.deadline === null && project.description === '' && project.status === 'ACTIVE', 'Clear deadline/description and status edit persist');
  await page.reload();
  await page.getByRole('heading', { name: title + ' — оновлено', exact: true }).waitFor();
  await page.setViewportSize({ width: 1280, height: 900 });
  assert(await page.locator('.tasks-table th').evaluateAll((cells) => cells.every((cell) => cell.getBoundingClientRect().width > 90)), 'All task columns must remain readable');
  await page.screenshot({ path: '.tmp/tasko-project-details.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Details must fit mobile width');
  await page.screenshot({ path: '.tmp/tasko-project-details-mobile.png', fullPage: true });
  await page.getByRole('link', { name: 'Редагувати проєкт', exact: true }).click();
  await page.getByLabel('Назва проєкту', { exact: true }).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Form must fit mobile width');
  await page.getByLabel('Статус', { exact: true }).selectOption('COMPLETED');
  await page.getByRole('button', { name: 'Зберегти проєкт' }).click();
  await page.getByRole('alert').filter({ hasText: 'Спочатку завершіть' }).waitFor();
  await page.getByLabel('Статус', { exact: true }).selectOption('CANCELLED');
  await page.getByRole('button', { name: 'Зберегти проєкт' }).click();
  await page.getByRole('heading', { name: title + ' — оновлено', exact: true }).waitFor();
  assert(await page.getByRole('link', { name: 'Редагувати проєкт', exact: true }).count() === 0, 'Closed project hides edit');
  await page.goto(baseUrl + `/projects/${id}/edit`);
  await page.getByRole('heading', { name: 'Редагування недоступне' }).waitFor();
  await page.setViewportSize({ width: 1280, height: 900 });
  await signIn(freelancer);
  await page.goto(baseUrl + `/projects/${id}`);
  await page.getByRole('cell', { name: 'Перевірити головну сторінку', exact: true }).waitFor();
  await page.goto(baseUrl + '/projects/new');
  await page.getByRole('heading', { name: 'Редагування недоступне' }).waitFor();
  await call('patch', `/projects/${id}`, { title: 'Заборонена зміна' }, freelancer.token, 403);
  await signIn(outsider);
  await page.goto(baseUrl + `/projects/${id}`);
  await page.getByRole('alert').filter({ hasText: 'Немає доступу' }).waitFor();
  await call('get', `/projects/${id}/members`, undefined, outsider.token, 403);
  await call('get', `/projects/${id}/tasks`, undefined, outsider.token, 403);
  await page.goto(baseUrl + '/projects/00000000-0000-4000-8000-000000000000');
  await page.getByRole('alert').filter({ hasText: 'Проєкт не знайдено' }).waitFor();
  assert(errors.length === 0, 'Browser errors: ' + errors.join(', '));
  await page.evaluate(() => sessionStorage.clear());
  await page.goto(baseUrl + '/login');
  console.log('Project create/edit/detail checks passed against real API and PostgreSQL; isolated fixtures preserved.');
}
